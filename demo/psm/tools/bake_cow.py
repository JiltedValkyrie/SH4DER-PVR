#!/usr/bin/env python3
"""Cut the fetched Spot (CC0, fetch_table.json) down to a low mesh for the Dreamcast program and write it as a C header.

  python demo/psm/tools/bake_cow.py <spot.obj> <out.h> [--tris 400]

The Dreamcast draws this mesh on screen and into the SH-4's shadow map each frame, twice (two cows), so it has to be
small: about 400 triangles a cow. The cut is vertex clustering: vertices that fall in one cell of a grid become their
mean, triangles that lose a corner go, and the grid is the finest one that stays under the budget. Crude and
deterministic; no library needed. The mesh is scaled to a longest side of 1, centred in x and z, feet on y = 0.

Nothing is vendored: the header goes to the build folder. Without the fetched file the program builds a stand-in from
boxes (psm_scene.h, no PSM_HAVE_COW).
"""
import sys


def read_obj(path):
    verts, tris = [], []
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            p = line.split()
            if not p:
                continue
            if p[0] == "v" and len(p) >= 4:
                verts.append((float(p[1]), float(p[2]), float(p[3])))
            elif p[0] == "f" and len(p) >= 4:
                idx = [int(q.split("/")[0]) for q in p[1:]]
                idx = [i - 1 if i > 0 else len(verts) + i for i in idx]
                for k in range(1, len(idx) - 1):
                    tris.append((idx[0], idx[k], idx[k + 1]))
    return verts, tris


def normalise(verts):
    lo = [min(v[k] for v in verts) for k in range(3)]
    hi = [max(v[k] for v in verts) for k in range(3)]
    s = 1.0 / max(hi[k] - lo[k] for k in range(3))
    cx, cz = 0.5 * (lo[0] + hi[0]), 0.5 * (lo[2] + hi[2])
    return [((v[0] - cx) * s, (v[1] - lo[1]) * s, (v[2] - cz) * s) for v in verts]


def cluster(verts, tris, cell):
    key_of, groups = [], {}
    for v in verts:
        k = (int(v[0] // cell), int(v[1] // cell), int(v[2] // cell))
        key_of.append(k)
        groups.setdefault(k, []).append(v)
    index, out_v = {}, []
    for k in sorted(groups):
        g = groups[k]
        index[k] = len(out_v)
        out_v.append(tuple(sum(p[c] for p in g) / len(g) for c in range(3)))
    seen, out_t = set(), []
    for a, b, c in tris:
        ia, ib, ic = index[key_of[a]], index[key_of[b]], index[key_of[c]]
        if ia == ib or ib == ic or ia == ic:
            continue
        s = tuple(sorted((ia, ib, ic)))
        if s in seen:
            continue
        seen.add(s)
        out_t.append((ia, ib, ic))
    used = sorted({i for t in out_t for i in t})
    remap = {i: n for n, i in enumerate(used)}
    return [out_v[i] for i in used], [tuple(remap[i] for i in t) for t in out_t]


def normals(verts, tris):
    acc = [[0.0, 0.0, 0.0] for _ in verts]
    for a, b, c in tris:
        p, q, r = verts[a], verts[b], verts[c]
        e1 = [q[k] - p[k] for k in range(3)]
        e2 = [r[k] - p[k] for k in range(3)]
        n = (e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0])
        for i in (a, b, c):
            for k in range(3):
                acc[i][k] += n[k]
    out = []
    for n in acc:
        length = (n[0] * n[0] + n[1] * n[1] + n[2] * n[2]) ** 0.5
        out.append(tuple(x / length for x in n) if length > 1e-12 else (0.0, 1.0, 0.0))
    return out


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 2
    budget = 400
    if "--tris" in argv:
        budget = int(argv[argv.index("--tris") + 1])
    verts, tris = read_obj(argv[1])
    if not verts or not tris:
        print("bake_cow: no mesh in", argv[1])
        return 1
    verts = normalise(verts)
    lo, hi = 0.005, 0.5                      # the cell: bisect for the finest grid under the budget
    for _ in range(24):
        mid = 0.5 * (lo + hi)
        if len(cluster(verts, tris, mid)[1]) > budget:
            lo = mid
        else:
            hi = mid
    v, t = cluster(verts, tris, hi)
    n = normals(v, t)
    if len(v) > 65535 or not t:
        print("bake_cow: bad result")
        return 1
    with open(argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by demo/psm/tools/bake_cow.py from Spot (Keenan Crane, CC0 1.0). Not in the repository. */\n")
        f.write("#define PSM_COW_V %du\n#define PSM_COW_T %du\n" % (len(v), len(t)))
        f.write("static const float psm_cow_v[PSM_COW_V][3] = {\n")
        f.write("".join("    { %.5ff, %.5ff, %.5ff },\n" % p for p in v))
        f.write("};\nstatic const float psm_cow_n[PSM_COW_V][3] = {\n")
        f.write("".join("    { %.4ff, %.4ff, %.4ff },\n" % p for p in n))
        f.write("};\nstatic const unsigned short psm_cow_t[PSM_COW_T][3] = {\n")
        f.write("".join("    { %d, %d, %d },\n" % p for p in t))
        f.write("};\n")
    print("bake_cow: %d source triangles -> %d vertices, %d triangles (budget %d, cell %.4f)" % (len(tris), len(v), len(t), budget, hi))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
