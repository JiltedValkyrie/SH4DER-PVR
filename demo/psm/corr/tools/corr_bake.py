#!/usr/bin/env python3
"""corr-a's textures: the corridor's four tiles, upscaled, with mip levels, as a C header for the program.

    python demo/psm/corr/tools/corr_bake.py --out DIR      writes DIR/corr_tex_data.h (refuses an existing file)
    python demo/psm/corr/tools/corr_bake.py --self-test    checks the twiddle and the mip layout, writes nothing

Copyright (c) 2026 Jilted Valkyrie. See ../../../../LICENSE.

The tiles (Retro Textures Fantasy, Kenney, CC0: ../CREDITS.md) are 64 x 64 (a metre square: the floor, the ceiling) or
64 x 128 (a metre wide, two high: the wall, the gate; two of them side by side make a 2 m square, 0.5 of a repeat a metre). They are scaled up by NEAREST, so the texel
grid stays sharp and the blur at a grazing angle shows plainly: the floor and the walls to 256 x 256 and to 128 x 128
(the size key), the ceiling and the doorway to 128 x 128 (the wall tile turned a quarter: TEXTURES). Each texture is a full mip chain: every level a box filter of
the level-0 image (for a nearest x2 / x4 upscale the levels down to 64 x 64 are the tile itself), RGB565, twiddled, in
the PVR's layout (the 1 x 1 level at byte 6, as ../../ao/mip_model.h has it). The art is read from
../assets/kenney_retro-textures-fantasy (fetch: ../../../pl4nar/tools/fetch.py --root demo/psm/corr). Needs Pillow.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CORR = os.path.dirname(HERE)
ART = os.path.join(CORR, "assets", "kenney_retro-textures-fantasy")

MIP_WORDS = [0x3, 0x4, 0x8, 0x18, 0x58, 0x158, 0x558, 0x1558, 0x5558, 0x15558]   # start of each level, 16-bit words

# name in C, source file, side, turned. Every surface's v runs along the corridor (a later stretched-copy mode halves
# along v only: ../../fakeaf.h), so a wall tile is turned a quarter: on the wall its rows then run up, its bricks level.
TEXTURES = [
    ("corr_tex_floor256", "floor_stone_pattern.png", 256, 0),
    ("corr_tex_wall256", "wall_brick_stone_center.png", 256, 1),
    ("corr_tex_floor128", "floor_stone_pattern.png", 128, 0),
    ("corr_tex_wall128", "wall_brick_stone_center.png", 128, 1),
    ("corr_tex_ceil128", "floor_wood_planks_wide.png", 128, 0),
    ("corr_tex_door128", "door_metal_gate.png", 128, 0),
]


def twid(x, y, bits):
    o = 0
    for i in range(bits):
        o |= ((y >> i) & 1) << (2 * i)
        o |= ((x >> i) & 1) << (2 * i + 1)
    return o


def rgb565(px):
    return ((px[0] >> 3) << 11) | ((px[1] >> 2) << 5) | (px[2] >> 3)


def chain_words(side):
    return MIP_WORDS[side.bit_length() - 1] + side * side


def mip_twiddled(im):
    from PIL import Image
    n = im.size[0]
    top = n.bit_length() - 1
    words = [0] * chain_words(n)
    for lvl in range(top + 1):
        s = 1 << lvl
        m = im if s == n else im.resize((s, s), Image.BOX)
        px = m.load()
        for y in range(s):
            for x in range(s):
                words[MIP_WORDS[lvl] + twid(x, y, lvl)] = rgb565(px[x, y])
    words[0] = words[1] = words[2] = words[MIP_WORDS[0]]   # the bytes before the 1 x 1 level
    return words


def self_test():
    assert twid(1, 0, 8) == 2 and twid(0, 1, 8) == 1 and twid(255, 255, 8) == 0xffff
    assert chain_words(256) * 2 == 0x2aab0, hex(chain_words(256) * 2)   # mip_model.h's MIP_BYTES
    assert chain_words(128) * 2 == 0xaab0
    for k in range(1, 9):                                               # each level follows the one before it
        assert MIP_WORDS[k] == MIP_WORDS[k - 1] + (1 << (2 * (k - 1)))
    print("CORR_BAKE_SELF_TEST_OK")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        self_test()
        return 0
    if not a.out:
        ap.error("--out DIR")
    from PIL import Image
    path = os.path.join(a.out, "corr_tex_data.h")
    if os.path.exists(path):
        print("refused: %s exists" % path)
        return 1
    os.makedirs(a.out, exist_ok=True)
    out = ["/* corr-a textures, generated by demo/psm/corr/tools/corr_bake.py: do not edit, do not commit.",
           "   Art: Retro Textures Fantasy by Kenney (kenney.nl), CC0 1.0 (demo/psm/corr/CREDITS.md). */",
           "#ifndef CORR_TEX_DATA_H", "#define CORR_TEX_DATA_H", "#include <stdint.h>"]
    for name, src, side, turned in TEXTURES:
        rgba = Image.open(os.path.join(ART, src)).convert("RGBA")   # the gate has see-through texels: the dark room behind
        im = Image.alpha_composite(Image.new("RGBA", rgba.size, (12, 10, 8, 255)), rgba).convert("RGB")
        if im.size == (64, 128):                       # a 1 m x 2 m tile (the wall, the gate): two side by side, 2 m square
            sq = Image.new("RGB", (128, 128))
            sq.paste(im, (0, 0))
            sq.paste(im, (64, 0))
            im = sq
        if im.size not in ((64, 64), (128, 128)):
            print("refused: %s is %dx%d, not 64x64 or 64x128" % (src, im.size[0], im.size[1]))
            return 1
        if turned:
            im = im.transpose(Image.ROTATE_90)
        words = mip_twiddled(im.resize((side, side), Image.NEAREST))
        out.append("#define %s_SIDE %du" % (name.upper(), side))
        out.append("static const uint16_t %s[%d] __attribute__((aligned(32))) = {" % (name, len(words)))
        for k in range(0, len(words), 16):
            out.append("  " + ",".join("0x%04x" % w for w in words[k:k + 16]) + ",")
        out.append("};")
    out.append("#endif")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s (%d textures)" % (path, len(TEXTURES)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
