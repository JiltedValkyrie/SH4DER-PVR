#!/usr/bin/env python3
"""Generate five original low-poly OBJ models for the SH4DER demo.

Writes models/dude.obj, wagon.obj, jet.obj, crate.obj, lamp.obj (next to tools/).
Deterministic, standard library only. If ANY target already exists the script
refuses (exit 1) and writes nothing.

Geometry: every part is the convex hull of a few points (box, wedge, flat plate).
Each hull is split into triangles. Normals are flat per triangle, outward,
and the winding is counter-clockwise seen from outside (matches the normal).
Each part is an OBJ object ('o') with its own material name ('usemtl').
tools/obj2c.py takes the colour from the material name (crc32), not from a .mtl
file, so no .mtl is written.
"""
import itertools
import math
import os

TOOLS_DIR = os.path.dirname(os.path.abspath(__file__))
MODELS_DIR = os.path.join(os.path.dirname(TOOLS_DIR), 'models')
EPS = 1e-7


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def unit(a):
    n = math.sqrt(dot(a, a))
    return (a[0] / n, a[1] / n, a[2] / n)


def box(lo, hi):
    """Eight corners of an axis-aligned box."""
    return [(x, y, z) for x in (lo[0], hi[0]) for y in (lo[1], hi[1]) for z in (lo[2], hi[2])]


def plate(quad, z0, dz):
    """Flat quad given as (x, y) corners, at height z0, thickened upward by dz."""
    pts = []
    for x, y in quad:
        pts.append((x, y, z0))
        pts.append((x, y, z0 + dz))
    return pts


def rot_y(pts, deg):
    c = math.cos(math.radians(deg))
    s = math.sin(math.radians(deg))
    return [(x * c + z * s, y, -x * s + z * c) for (x, y, z) in pts]


def move(pts, d):
    return [(x + d[0], y + d[1], z + d[2]) for (x, y, z) in pts]


def hull_faces(pts):
    """Convex hull faces of pts: list of polygons (point lists), each CCW seen from outside."""
    n = len(pts)
    seen = set()
    faces = []
    for i, j, k in itertools.combinations(range(n), 3):
        a, b, c = pts[i], pts[j], pts[k]
        nrm = cross(sub(b, a), sub(c, a))
        if dot(nrm, nrm) < 1e-18:
            continue
        nrm = unit(nrm)
        d = dot(nrm, a)
        s = [dot(nrm, p) - d for p in pts]
        if max(s) > EPS and min(s) < -EPS:
            continue  # plane cuts through the point set: not a hull face
        if max(s) > EPS:
            # all points on the negative side after flipping: nrm points outward
            nrm = (-nrm[0], -nrm[1], -nrm[2])
            s = [-v for v in s]
        on = [m for m in range(n) if abs(s[m]) <= EPS]
        if len(on) < 3:
            continue
        key = tuple(on)
        if key in seen:
            continue
        seen.add(key)
        pc = tuple(sum(pts[m][t] for m in on) / len(on) for t in range(3))
        ref = (1.0, 0.0, 0.0) if abs(nrm[0]) < 0.9 else (0.0, 1.0, 0.0)
        u = unit(cross(nrm, ref))
        v = cross(nrm, u)

        def ang(m):
            d_ = sub(pts[m], pc)
            return math.atan2(dot(d_, v), dot(d_, u))

        order = sorted(on, key=ang)
        faces.append([pts[m] for m in order])
    return faces


class Model:
    def __init__(self, name):
        self.name = name
        self.parts = []  # (part name, material name, [triangle, ...]) ; triangle = 3 points

    def add(self, part, mat, pts):
        tris = []
        for face in hull_faces(pts):
            for k in range(1, len(face) - 1):
                tris.append((face[0], face[k], face[k + 1]))
        self.parts.append((part, mat, tris))

    def text(self):
        out = ['# %s: generated by tools/make_models.py (original geometry)' % self.name,
               'o %s' % self.name]
        vi = 0
        ni = 0
        for part, mat, tris in self.parts:
            out.append('o %s' % part)
            out.append('usemtl %s' % mat)
            for a, b, c in tris:
                n = unit(cross(sub(b, a), sub(c, a)))
                ni += 1
                for p in (a, b, c):
                    out.append('v %.5f %.5f %.5f' % p)
                out.append('vn %.5f %.5f %.5f' % n)
                out.append('f %d//%d %d//%d %d//%d' % (vi + 1, ni, vi + 2, ni, vi + 3, ni))
                vi += 3
        return '\n'.join(out) + '\n'

    def triangle_count(self):
        return sum(len(t) for _, _, t in self.parts)


def dude():
    m = Model('dude')
    for side, tag, y0, y1 in ((1, 'L', 0.035, 0.105), (-1, 'R', -0.105, -0.035)):
        m.add('foot_' + tag, 'dude_boot', box((-0.02, y0, 0.00), (0.10, y1, 0.04)))
        m.add('shin_' + tag, 'dude_shin', box((-0.04, y0, 0.04), (0.04, y1, 0.20)))
        m.add('thigh_' + tag, 'dude_thigh', box((-0.045, y0, 0.20), (0.045, y1, 0.37)))
        ya0, ya1 = (0.16, 0.22) if side > 0 else (-0.22, -0.16)
        m.add('arm_' + tag, 'dude_arm', box((-0.03, ya0, 0.40), (0.03, ya1, 0.56)))
        fore = rot_y(box((-0.025, -0.025, -0.16), (0.025, 0.025, 0.0)), -25.0)
        m.add('forearm_' + tag, 'dude_forearm', move(fore, (0.0, side * 0.19, 0.40)))
    m.add('pelvis', 'dude_pelvis', box((-0.07, -0.13, 0.36), (0.07, 0.13, 0.44)))
    m.add('chest', 'dude_chest', box((-0.075, -0.13, 0.44), (0.075, 0.13, 0.58)))
    m.add('neck', 'dude_neck', box((-0.03, -0.035, 0.58), (0.03, 0.035, 0.605)))
    m.add('head', 'dude_head', box((-0.06, -0.06, 0.605), (0.07, 0.06, 0.69)))
    return m


def wagon():
    m = Model('wagon')
    paint, glass = 'wagon_paint', 'wagon_glass'
    m.add('body_lower', paint, box((-1.87, -0.52, 0.20), (0.88, 0.52, 0.70)))
    m.add('cabin', paint, box((-1.87, -0.52, 0.70), (0.22, 0.52, 1.00)))
    m.add('tailgate', 'wagon_tailgate', box((-1.90, -0.52, 0.20), (-1.87, 0.52, 1.00)))
    m.add('glass_L', glass, box((-1.84, 0.50, 0.76), (0.19, 0.535, 0.92)))
    m.add('glass_R', glass, box((-1.84, -0.535, 0.76), (0.19, -0.50, 0.92)))
    m.add('windscreen', glass, box((0.19, -0.45, 0.76), (0.235, 0.45, 0.95)))
    m.add('rack_L', 'wagon_rack', box((-1.75, 0.40, 1.00), (0.15, 0.45, 1.03)))
    m.add('rack_R', 'wagon_rack', box((-1.75, -0.45, 1.00), (0.15, -0.40, 1.03)))
    for xc in (-1.45, 0.35):
        for s in (1, -1):
            y0, y1 = (0.41, 0.55) if s > 0 else (-0.55, -0.41)
            m.add('tyre', 'wagon_tyre', box((xc - 0.18, y0, 0.0), (xc + 0.18, y1, 0.36)))
            yh0, yh1 = (0.55, 0.57) if s > 0 else (-0.57, -0.55)
            m.add('hub', 'wagon_hub', box((xc - 0.09, yh0, 0.09), (xc + 0.09, yh1, 0.27)))
    m.add('bumper_rear', 'wagon_bumper', box((-1.90, -0.55, 0.22), (-1.84, 0.55, 0.32)))
    m.add('bumper_front', 'wagon_bumper', box((0.84, -0.55, 0.22), (0.90, 0.55, 0.34)))
    m.add('grille', 'wagon_grille', box((0.87, -0.30, 0.36), (0.90, 0.30, 0.44)))
    m.add('headlamp_L', 'wagon_lamp', box((0.87, 0.34, 0.46), (0.90, 0.48, 0.56)))
    m.add('headlamp_R', 'wagon_lamp', box((0.87, -0.48, 0.46), (0.90, -0.34, 0.56)))
    return m


def jet():
    m = Model('jet')
    m.add('fuselage', 'jet_grey', box((-4.4, -0.5, 0.45), (3.2, 0.5, 1.05)))
    m.add('nose', 'jet_grey', [(3.2, -0.5, 0.45), (3.2, 0.5, 0.45), (3.2, -0.5, 1.05),
                               (3.2, 0.5, 1.05), (5.0, 0.0, 0.75)])
    m.add('canopy', 'jet_glass', box((0.6, -0.36, 1.05), (2.4, 0.36, 1.35)))
    m.add('intake_L', 'jet_intake', box((0.0, 0.5, 0.45), (2.0, 0.7, 0.85)))
    m.add('intake_R', 'jet_intake', box((0.0, -0.7, 0.45), (2.0, -0.5, 0.85)))
    # vertical fin: quad in XZ, thickness 0.12 in Y
    fin_xz = [(-3.0, 1.05), (-4.4, 1.05), (-4.6, 3.3), (-3.8, 3.3)]
    fin = [(x, y, z) for (x, z) in fin_xz for y in (-0.06, 0.06)]
    m.add('fin', 'jet_tail', fin)
    m.add('ventral_fin', 'jet_tail', box((-4.2, -0.06, 0.30), (-3.4, 0.06, 0.45)))
    for s in (1, -1):
        tag = 'L' if s > 0 else 'R'
        m.add('tailplane_' + tag, 'jet_grey',
              plate([(-2.9, 0.5 * s), (-4.4, 0.5 * s), (-4.4, 1.6 * s), (-3.4, 1.6 * s)], 0.80, 0.12))
        m.add('wing_' + tag, 'jet_wing',
              plate([(1.0, 0.5 * s), (-1.6, 0.5 * s), (-2.0, 3.8 * s), (-0.6, 3.8 * s)], 0.60, 0.10))
        y0, y1 = (3.70, 3.80) if s > 0 else (-3.80, -3.70)
        m.add('winglet_' + tag, 'jet_tail', box((-1.95, y0, 0.60), (-0.95, y1, 1.00)))
        y0, y1 = (0.10, 0.46) if s > 0 else (-0.46, -0.10)
        m.add('nozzle_' + tag, 'jet_nozzle', box((-5.0, y0, 0.10), (-4.4, y1, 0.80)))
        py0, py1 = (1.95, 2.15) if s > 0 else (-2.15, -1.95)
        my0, my1 = (1.99, 2.11) if s > 0 else (-2.11, -1.99)
        m.add('pylon_' + tag, 'jet_pylon', box((-1.0, py0, 0.42), (0.0, py1, 0.60)))
        m.add('missile_' + tag, 'jet_missile', box((-0.9, my0, 0.30), (0.2, my1, 0.42)))
    return m


def crate():
    m = Model('crate')
    m.add('body_low', 'crate_wood', box((-0.22, -0.355, 0.00), (0.22, 0.355, 0.33)))
    m.add('band', 'crate_band', box((-0.21, -0.345, 0.33), (0.21, 0.345, 0.42)))
    m.add('body_high', 'crate_wood', box((-0.22, -0.355, 0.42), (0.22, 0.355, 0.77)))
    return m


def lamp():
    m = Model('lamp')
    m.add('base', 'lamp_base', box((-0.20, -0.20, 0.00), (0.20, 0.20, 0.06)))
    m.add('post', 'lamp_post', box((-0.03, -0.03, 0.06), (0.03, 0.03, 1.00)))
    gus = [(x, y, z) for (x, z) in ((0.03, 0.06), (0.03, 0.20), (0.12, 0.06)) for y in (-0.02, 0.02)]
    m.add('gusset', 'lamp_post', gus)
    m.add('housing', 'lamp_housing', box((-0.12, -0.19, 0.88), (0.15, 0.19, 1.14)))
    m.add('glow', 'lamp_glow', box((0.15, -0.16, 0.91), (0.17, 0.16, 1.11)))
    return m


def main():
    models = [dude(), wagon(), jet(), crate(), lamp()]
    paths = [os.path.join(MODELS_DIR, m.name + '.obj') for m in models]
    existing = [p for p in paths if os.path.exists(p)]
    if existing:
        for p in existing:
            print('REFUSED: already exists, not overwritten: %s' % p)
        return 1
    os.makedirs(MODELS_DIR, exist_ok=True)
    for m, p in zip(models, paths):
        with open(p, 'x', encoding='ascii', newline='\n') as f:
            f.write(m.text())
        print('wrote %s  (%d triangles, %d parts)' % (p, m.triangle_count(), len(m.parts)))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
